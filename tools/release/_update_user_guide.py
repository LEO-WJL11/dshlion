#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""给安装包里的《使用说明.md》补上 1.5.3/1.5.4 的新东西。

【为什么要补】这份文档是**装完就会看到**的那份说明，但它还停在 1.5.2 之前：
里面一次都没提 VS Code 右侧栏、改动人工审核、16K 上下文、`@` 引用、插件管理。
用户照着旧说明找按钮，找不到 —— 这比没有说明更糟。

【做法】在开头插入一节"这一版怎么用"（最短路径），再补两节细节（审核 / 上下文），
不动原文其余部分（那些关于安装目录、模型下载、端口的内容还是对的）。
"""

import io
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
P = os.path.join(ROOT, 'dist', '使用说明.md')

HEAD = '''> **这一版（1.5.4）最重要的三件事** —— 装完照这三条走就行：
>
> 1. **客户端就在 VS Code 里**：安装时已经自动装好插件，打开 VS Code，
>    **最右边那一栏**（secondary sidebar）就是「LionBox Agent」。不用再跳浏览器。
>    插件没装上（比如 VS Code 装在奇怪的位置）就手动装：设置 → 扩展 → ... → 从 VSIX 安装，
>    文件在安装目录的 `vscode-extension\\LionBox-VSCode.vsix`；装没装成功看同目录的
>    `install-result.txt`。
> 2. **工作区 = 你在 VS Code 里打开的那个文件夹**，不用手填路径。想少花上下文就 `@` 引用
>    单个文件（只读那一个文件进去）。
> 3. **AI 改的文件要你点「通过」才真正落盘**：改动会先出现在对话框上方（WebUI）或面板里
>    （VS Code），带 diff；点「通过并写入」才写进磁盘，点「打回」写句理由，它会照着重写。
>    不想要这道闸门：设置 → 插件管理 → 改动人工审核，关掉即可。

## 在 VS Code 里怎么用（右侧栏 Agent）

| 想干什么 | 怎么做 |
| --- | --- |
| 让它干活 | 在面板输入框里说，`Ctrl+Enter` 发送 |
| 只把一个文件给它看 | 点「@ 文件」挑一个 —— 只这个文件进上下文，省窗口 |
| 看它改了什么 | 面板上方列出待审改动，每条带 diff（`+` 绿 / `-` 红） |
| 让它改 | 点「通过并写入」 |
| 让它重写 | 点「打回」，输入理由（理由会回给模型） |
| 换项目 | 在 VS Code 里打开另一个文件夹 —— 工作区和会话自动跟着换 |
| 想用完整界面 | 面板右上角「Web」按钮，或开始菜单启动 LionBox 后开 `http://127.0.0.1:8080` |

## 上下文窗口：默认 16K（这是刻意的）

模型原生支持 256K，但**每一条消息都要把整个前缀重新算一遍**（预填充），窗口越大越慢。
所以默认只给 16K：

- 一般的活 16K 够用，速度也快；
- **真的装不下时，模型自己会调大**（它有个 `context_window` 工具），干完会自动调回来；
  你也可以手动改：输入框下面点「窗口 16K」；
- 前面那些翻文件、试错的过程没用了，模型会用 `context_prune` **真删掉**（只留最近几条），
  这样后面每一轮都更省。

## 插件都在「设置 → 插件管理」一页里

九类插件（基础工具 / 进阶工具 / 技能 / 终端 / 大循环 / 子智能体 / 智能体团队 /
授权审查 / 自动化任务），每个插件一行开关，**它自己的参数就在那一行下面**（可折叠）：
终端限制、大循环轮数、子智能体层级、团队成员、自动化任务……都在这里改。
打开「插件开发模式」还能生成插件骨架，改完点「重新加载插件」即时生效，不用重启。

'''

s = io.open(P, encoding='utf-8', newline='').read()
if 'secondary sidebar' in s or '最右边那一栏' in s:
    print('使用说明已补过，跳过')
    sys.exit(0)
nl = '\r\n' if '\r\n' in s else '\n'
body = HEAD.replace('\n', nl)
io.open(P, 'w', encoding='utf-8', newline='').write(body + nl + s.lstrip())
print('已给 dist/使用说明.md 补上 1.5.3/1.5.4 的新功能（插在最前面）')
