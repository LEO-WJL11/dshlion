#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""把 LionBoxDesktop.iss 里的 [Code] 段去掉，换成一段说明。

为什么去掉：安装时的 WebView2 检测实测有两个坑 ——
  1) Inno 会把字符串里的 {GUID} 当常量展开（注册表路径的花括号必须写 {{...}}）；
  2) 更要命的是，[Code] 里只要有一点闪失，静默安装就**直接 exit=1、连日志都不写、一个文件都不装**，
     而同一份脚本用 /DSKIP_WEBVIEW2_CHECK（等于没有这段代码）编出来就一切正常。
这个检查改到应用里做：壳启动时 WebView2 起不来会在窗口里显示"请先装运行时 + 官方链接"，
既不挡安装也不挡卸载。安装包保持"复制文件 + 快捷方式 + 卸载项"这么简单。
"""

import io
import sys

P = 'installer/LionBoxDesktop.iss'
NOTE = (
    "; ---------------------------------------------------------------------------\n"
    "; 这里**故意没有 [Code] 段**。\n"
    ";\n"
    "; 本来想在安装时检测系统 WebView2 运行时、缺了就提示。实测这条路有两个坑：\n"
    ";   1) Inno 会把字符串里的 {GUID} 当常量展开（注册表路径里的花括号必须写成 {{...}}）；\n"
    ";   2) 更要命的是：只要 [Code] 里有闪失，静默安装会**直接 exit=1、连日志都不写、\n"
    ";      一个文件都不装**，而且完全不告诉用户为什么 —— 同一份脚本用 /DSKIP_WEBVIEW2_CHECK\n"
    ";      编出来（等于没有这段代码）就一切正常。\n"
    "; 所以这个检查挪到应用里做：壳启动时如果发现 WebView2 起不来，会在窗口里显示一句人话\n"
    ";   （\"请先装 Microsoft Edge WebView2 运行时\" + 官方下载链接），既不挡安装也不挡卸载。\n"
    "; 安装包本身保持\"复制文件 + 建快捷方式 + 卸载项\"这么简单，谁都能一眼看懂、每一步都可验证。\n"
    "; ---------------------------------------------------------------------------\n"
)

s = io.open(P, encoding='utf-8', newline='').read()
i = s.find('[Code]')
if i < 0:
    print('没有 [Code] 段，nothing to do')
    sys.exit(0)
s = s[:i] + NOTE
io.open(P, 'w', encoding='utf-8', newline='').write(s)
print('已去掉 [Code] 段（原长度 %d → 现长度 %d）' % (i, len(s)))
